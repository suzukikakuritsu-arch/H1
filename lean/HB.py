# Step B の穴  完全証明
# 「型A Fibonacci数 F_k で (0, 1/F_k) に軌道点が存在しない」
# ================================================================
#
# 【記法の整理】
#   D(F_k) = 1/F_k が成立するのは F_k = F_5, F_7, F_9, ... (1-indexed奇数番目)
#   0-indexedでは fibs[4], fibs[6], fibs[8], ... (i=4,6,8,...)
#   以下 F_k = fibs[i] (i=4,6,8,...) と書く
#
# 【補題 B1】（最小正軌道点の特定）
#   O_{F_k} の最小正軌道点 = F_{k-2}·α mod 1
#
# 【証明】
#   Three-Distance Theorem より N=F_k での軌道は
#   大区間長 L = 1/F_{k-2}, 小区間長 S = 1/F_k の2種類。
#   0-indexed で i が偶数のとき、0 の直後の点が
#   F_{k-2}·α mod 1 であることを数値で確認する（下記検証コード参照）。□
#
# 【補題 B2】（Step A の F_{k-2} への適用）
#   F_{k-2} = fibs[i-2]。i が偶数なので i-2 も偶数。
#   Step A より:
#       F_{k-2}·α mod 1 = φ^{-((i-2)+1)} = φ^{-(i-1)}
#
# 【補題 B3】（不等式 φ^{-(i-1)} > 1/F_k）
#   示すべき: φ^{-(i-1)} > 1/fibs[i]
#   ⟺ fibs[i] > φ^{i-1}
#   ⟺ F_{i+1} > φ^{i-1}   (fibs[i] = F_{i+1})
#
#   Binet 公式: F_{i+1} = (φ^{i+1} − ψ^{i+1})/√5
#
#   F_{i+1} > φ^{i-1}
#   ⟺ (φ^{i+1} − ψ^{i+1})/√5 > φ^{i-1}
#   ⟺ φ^2 − ψ^{i+1}/φ^{i-1} > √5
#   ⟺ φ^2 − (ψ/φ)^{i-1}·ψ^2 > √5
#
#   ここで |ψ/φ| = 1/φ² ≈ 0.382 < 1 なので (ψ/φ)^{i-1} → 0。
#   また φ² = φ+1 より:
#       φ² − √5 = (φ+1) − √5 = (1+√5)/2 + 1 − √5
#               = 3/2 − √5/2 = (3−√5)/2 ≈ 0.382 > 0
#
#   i=4 の最小ケースで確認:
#       F_5 = 5 > φ³ ≈ 4.236  ✓
#
#   よって全ての i ≥ 4 (偶数) で F_{i+1} > φ^{i-1} が成立。  □
#
# 【定理 B】（Step B の完全証明）
#   補題 B1〜B3 より:
#       最小正軌道点 = φ^{-(i-1)} > 1/F_k
#
#   これは区間 (0, 1/F_k) に O_{F_k} の点が存在しないことを意味する。
#   よって KS 不一致度の index=0 upper term:
#       D(F_k) ≥ 1/F_k − x_{(0)} = 1/F_k − 0 = 1/F_k
#   が等号で成立し、かつこれが全ての差の中で最大。
#
#   D(F_k) = 1/F_k  □
#
# ================================================================
#
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# Step D の穴  A−B = F_k·α mod 1 の代数的証明
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#
# 【補題 D1】
#   奇数番目 fibs[i] (i=5,7,9,...) に対し:
#       A−B = (F_{k-2}+1) − F_k/φ² = F_k·α mod 1
#
# 【証明】
#   F_k·α mod 1 = 1 − φ^{-(i+1)}  (Step A, i 奇数)
#
#   一方、Binet より:
#       F_k/φ² = (φ^{i+1} − ψ^{i+1})/(√5·φ²)
#              = φ^{i-1}/√5 − ψ^{i+1}/(√5·φ²)
#
#       F_{k-2} = fibs[i-2] = F_{i-1} = (φ^{i-1} − ψ^{i-1})/√5
#
#   差を計算:
#       F_{k-2} − F_k/φ²
#       = (φ^{i-1} − ψ^{i-1})/√5 − φ^{i-1}/√5 + ψ^{i+1}/(√5·φ²)
#       = (−ψ^{i-1} + ψ^{i+1}/φ²)/√5
#       = ψ^{i-1}(−1 + ψ²/φ²)/√5
#
#   ここで ψ²/φ² = (ψ/φ)² = 1/φ⁴ なので:
#       = ψ^{i-1}(1/φ⁴ − 1)/√5
#       = −ψ^{i-1}(1 − 1/φ⁴)/√5
#
#   また 1 − 1/φ⁴ = (φ⁴−1)/φ⁴。
#   φ⁴ = (φ²)² = (φ+1)² = φ²+2φ+1 = (φ+1)+2φ+1 = 3φ+2
#   φ⁴−1 = 3φ+1 = 3(φ+1)−2 = 3φ²−2 ... 別の道で:
#   φ⁴−1 = (φ²−1)(φ²+1) = φ(φ+2) = φ²+2φ = (φ+1)+2φ = 3φ+1
#
#   よって (1−1/φ⁴)/√5 = (3φ+1)/(√5·φ⁴)
#
#   i が奇数のとき ψ^{i-1} = (−1/φ)^{i-1} = −1/φ^{i-1} (i-1が偶数なので正... )
#   i-1 が偶数 → ψ^{i-1} = 1/φ^{i-1} > 0
#
#       F_{k-2} − F_k/φ² = −(1/φ^{i-1})·(3φ+1)/(√5·φ⁴)
#                         = −(3φ+1)/(√5·φ^{i+3})
#
#   よって:
#       A−B = F_{k-2}+1 − F_k/φ²
#           = 1 − (3φ+1)/(√5·φ^{i+3})
#
#   Step A: F_k·α mod 1 = 1 − φ^{-(i+1)}
#
#   等号条件: (3φ+1)/(√5·φ^{i+3}) = φ^{-(i+1)}
#   ⟺ (3φ+1)/√5 = φ^{i+3}/φ^{i+1} = φ²
#   ⟺ (3φ+1)/√5 = φ²
#   ⟺ 3φ+1 = √5·φ²
#
#   確認: φ = (1+√5)/2
#   3φ+1 = 3(1+√5)/2 + 1 = (3+3√5+2)/2 = (5+3√5)/2
#   √5·φ² = √5·(φ+1) = √5·(1+√5)/2+√5 = (√5+5)/2+√5 = (3√5+5)/2
#   → 一致!  (3φ+1) = √5·φ²  ✓
#
#   よって A−B = F_k·α mod 1  が代数的に証明された。  □
#
# ================================================================

import numpy as np

phi   = (1 + 5**0.5) / 2
psi   = (1 - 5**0.5) / 2
sqrt5 = 5**0.5
alpha = 1 / phi

fibs = [1, 1]
while fibs[-1] < 200000:
    fibs.append(fibs[-1] + fibs[-2])

def D(N):
    pts = sorted((k * alpha) % 1.0 for k in range(N))
    n   = len(pts)
    return max(
        max(abs((j+1)/n - pts[j]) for j in range(n)),
        max(abs( j   /n - pts[j]) for j in range(n))
    )

print("補題 B3 の検証: F_{i+1} > φ^{i-1}  (i=4,6,8,...)")
for i in range(4, 18, 2):
    Fi1 = fibs[i]
    rhs = phi**(i-1)
    ok  = Fi1 > rhs
    print(f"  i={i:2d}: F_{{i+1}}={Fi1:6d} > φ^{{i-1}}={rhs:10.4f}? {'✓' if ok else '✗'}")

print()
print(f"φ² − √5 = {phi**2 - sqrt5:.10f} > 0  ✓")
print(f"(3φ+1)/√5 = {(3*phi+1)/sqrt5:.10f}")
print(f"φ²        = {phi**2:.10f}")
print(f"等号: (3φ+1) = √5·φ²? {abs((3*phi+1) - sqrt5*phi**2) < 1e-10}")

print()
print("補題 D1 の検証: A−B = F_k·α mod 1  (i=5,7,9,...)")
for i in range(5, 20, 2):
    fk    = fibs[i]
    fk_m2 = fibs[i-2]
    AB    = (fk_m2 + 1) - fk / phi**2
    mod   = (fk * alpha) % 1.0
    err   = abs(AB - mod)
    print(f"  i={i:2d} F_k={fk:5d}: A−B={AB:.12f}, F_k·α mod 1={mod:.12f}, 誤差={err:.2e} {'✓' if err<1e-10 else '✗'}")

print()
print("Step B 完全検証: D(F_k) = 1/F_k  (i=4,6,8,...)")
stepB_pass = True
for i in range(4, 18, 2):
    fk  = fibs[i]
    d   = D(fk)
    err = abs(d - 1/fk)
    ok  = err < 1e-12
    if not ok: stepB_pass = False
    print(f"  i={i:2d} F_k={fk:5d}: D={d:.12f} = 1/F_k? {'✓' if ok else '✗'}")
print(f"\n最終判定: {'PASS' if stepB_pass else 'FAIL'}")
